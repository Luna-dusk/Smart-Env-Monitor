#define OLED_PAGES 8
#define OLED_WIDTH 128
#define OLED_HEIGHT 64
void oled_write_cmd(uint8_t cmd)
{
    uint8_t data[2] = {0,0};
    data[0] = 0x00;
    data[1] = cmd;  // 命令内容
    i2c_master_transmit(i2c_dev_handle,data,2,-1);
}
static void oled_write_data(const uint8_t *data, size_t len)
{
    uint8_t *buffer = (uint8_t *)malloc(len+1);
    buffer[0] = 0x40;
    memcpy(buffer+1,data,len);
    i2c_master_transmit(i2c_dev_handle, buffer, len + 1, -1);
    free(buffer);
}
static uint8_t oled_buffer[OLED_PAGES][OLED_WIDTH];
void oled_clear(void)
{
    memset(oled_buffer, 0x00, sizeof(oled_buffer));
}
void oled_show(void)
{
    oled_write_cmd(0x21);  // 列地址命令
    oled_write_cmd(0);     // 起始列
    oled_write_cmd(127);   // 结束列
    oled_write_cmd(0x22);  // 页地址命令
    oled_write_cmd(0);     // 起始页
    oled_write_cmd(7);     // 结束页

    // 把整个 1024 字节缓冲区发过去
    oled_write_data(&oled_buffer[0][0], OLED_WIDTH * OLED_PAGES);
}
void oled_draw_pixel(uint8_t x, uint8_t y)
{
    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) return;
    // 第 y/8 页，把该页的第 (y%8) 位置 1
    oled_buffer[y / 8][x] |= (1 << (y % 8));
}
void oled_show_char(uint8_t x, uint8_t y, char c)
{
    if (c < ' ' || c > '~') c = ' ';  // 不可打印字符显示空格
    for (uint8_t col = 0; col < 6; col++) {
        uint8_t line_data = font_6x8[(c - ' ') * 6 + col];
        // 字符宽度6像素，把字库数据写入缓冲区对应页
        oled_buffer[y / 8][x + col] = line_data;
    }
}
void oled_show_string(uint8_t x, uint8_t y, const char *str)
{
    while (*str) {
        oled_show_char(x, y, *str);
        x += 6;      // 一个字符占6像素宽
        if (x > OLED_WIDTH - 6) break;  // 超出屏幕就停止
        str++;
    }
}
void oled_init(void)
{
    oled_write_cmd(0xAE);  // 关闭显示
    oled_write_cmd(0xD5);  // 设置时钟分频
    oled_write_cmd(0x80);
    oled_write_cmd(0xA8);  // 设置多路复用比
    oled_write_cmd(0x3F);  // 64行
    oled_write_cmd(0xD3);  // 设置显示偏移
    oled_write_cmd(0x00);
    oled_write_cmd(0x40);  // 起始行地址
    oled_write_cmd(0x8D);  // 启用电荷泵
    oled_write_cmd(0x14);
    oled_write_cmd(0x20);  // 内存地址模式
    oled_write_cmd(0x00);  // 水平寻址模式
    oled_write_cmd(0xA1);  // 段重映射（左右翻转）
    oled_write_cmd(0xC8);  // COM扫描方向（上下翻转）
    oled_write_cmd(0xDA);  // COM引脚配置
    oled_write_cmd(0x12);
    oled_write_cmd(0x81);  // 对比度
    oled_write_cmd(0xCF);
    oled_write_cmd(0xD9);  // 预充电周期
    oled_write_cmd(0xF1);
    oled_write_cmd(0xDB);  // VCOMH电压
    oled_write_cmd(0x40);
    oled_write_cmd(0xA4);  // 显示内容来自GDDRAM
    oled_write_cmd(0xA6);  // 正常显示（不反转）
    oled_write_cmd(0xAF);  // 打开显示

    oled_clear();
    oled_show();
}


